"""Native, unsliced Bambu Studio projects written directly from mesh arrays.

No slicer dependency, external 3MF writer, or copied project template. Plate
records and build transforms follow Bambu's PartPlateList; each part's
filament is its model_settings ``extruder``, and bbs_3mf/FacetsAnnotation
triangle paint marks only the minority materials of a part that mixes them.
The Bambu application marker selects its native project loader (otherwise
it discards project configuration). Creator metadata identifies our exporter.
"""

