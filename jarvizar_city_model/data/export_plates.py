# Blender meshes are float32: six decimals round-trip every printable
# coordinate, and both sides of a seam format the identical float.
_VERTEX = '     <vertex x="%.6f" y="%.6f" z="%.6f"/>\n'
_TRIANGLE = '     <triangle v1="%d" v2="%d" v3="%d"%s/>\n'
_CHUNK = 65536
_COLOR = re.compile(r"^#[0-9A-F]{6}$")
_CONTENT_NS = "http://schemas.openxmlformats.org/package/2006/content-types"
_REL_NS = "http://schemas.openxmlformats.org/package/2006/relationships"


@dataclass(frozen=True)
class BambuPrinter:
    """Bed and starting presets, as named in Bambu Studio's bundled profiles."""

    key: str
    model: str
    width: float
    depth: float
    height: float
    print_profile: str
    filament_profile: str
    filament_id: str = "GFA00"  # Bambu PLA Basic
    filament_vendor: str = "Bambu Lab"
    filament_type: str = "PLA"

    @property
    def printer_profile(self):
        return f"{self.model} 0.4 nozzle"

    @property
    def bed(self):
        return f"{self.width:g} x {self.depth:g} mm"


